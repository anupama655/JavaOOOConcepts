public class ArraysExample { 
    public static void main(String[] args){ 
        int[] n={1,2,3,4,5}; 
        System.out.print("Values: "); 
        for(int x:n) 
            System.out.print(x+" "); 
        int[][] m={{1,2},{3,4}}; 
        System.out.println("\nMatrix[1][0]: "+m[1][0]); 
    } 
}
